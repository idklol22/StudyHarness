// Inline fonts/CSS/JS needed to render notes into one self-contained HTML file.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const katexDist = path.dirname(require.resolve('katex/dist/katex.min.css'));
const roughFile = path.join(path.dirname(require.resolve('roughjs/package.json')), 'bundled', 'rough.js');
let css = fs.readFileSync(path.join(katexDist, 'katex.min.css'), 'utf8');
css = css.replace(/url\(([^)]*?\.woff2)\)\s*format\("woff2"\)(?:,\s*url\([^)]*\)\s*format\("[^"]*"\))*/g, (m, u) => {
  const file = path.join(katexDist, u.replace(/['"]/g, ''));
  return `url(data:font/woff2;base64,${fs.readFileSync(file).toString('base64')}) format("woff2")`;
});
const font = (name) => `data:font/ttf;base64,${fs.readFileSync(path.join(root, 'src', 'fonts', name)).toString('base64')}`;
const out = `'use strict';\n// Generated by scripts/make-assets.mjs. Do not edit.\nmodule.exports = ${JSON.stringify({
  katexCss: css,
  roughSource: fs.readFileSync(roughFile, 'utf8'),
  fontRegular: font('Kalam-Regular.ttf'),
  fontBold: font('Kalam-Bold.ttf'),
})};\n`;
fs.mkdirSync(path.join(root, '.generated'), { recursive: true });
fs.writeFileSync(path.join(root, '.generated/assets.cjs'), out);
console.log(`Wrote assets (${(out.length / 1024).toFixed(0)} KiB)`);
